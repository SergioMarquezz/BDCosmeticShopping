CREATE OR REPLACE PACKAGE BODY PKG_USUARIOS AS

    -- CREAR USUARIO
    PROCEDURE CREAR_USUARIO(
        USER_NOMBRE IN VARCHAR2,
        USER_PATERNO IN VARCHAR2,
        USER_MATERNO IN VARCHAR2,
        USER_FECHA_NAC IN DATE,
        USER_TELEFONO IN VARCHAR2,
        USER_USUARIO IN VARCHAR2,
        USER_EMAIL IN VARCHAR2,
        USER_PASSWORD IN VARCHAR2,
        USER_ID_ROL IN NUMBER
    ) 
    AS
    BEGIN
        INSERT INTO TA_USUARIOS 
            (NOMBRE, AP_PATERNO, AP_MATERNO, FECHA_NACIMIENTO, TELEFONO, USUARIO, EMAIL, PASSWORD_HASH, ID_ROL, ESTADO)
        VALUES 
            (USER_NOMBRE, USER_PATERNO, USER_MATERNO, USER_FECHA_NAC, USER_TELEFONO, USER_USUARIO, USER_EMAIL, USER_PASSWORD, USER_ID_ROL, 'ACTIVO');
        
        COMMIT;
    END CREAR_USUARIO;

    -- ACTUALIZAR DATOS PERSONALES
    PROCEDURE UPDATE_USUARIO(
        USER_ID IN NUMBER,
        USER_NOMBRE IN VARCHAR2,
        USER_PATERNO IN VARCHAR2,
        USER_MATERNO IN VARCHAR2,
        USER_FECHA_NAC IN DATE,
        USER_TELEFONO IN VARCHAR2,
        USER_EMAIL IN VARCHAR2
    ) 
    AS
    BEGIN
        UPDATE TA_USUARIOS 
        SET 
            NOMBRE = USER_NOMBRE, 
            AP_PATERNO = USER_PATERNO, 
            AP_MATERNO = USER_MATERNO,
            FECHA_NACIMIENTO = USER_FECHA_NAC, 
            TELEFONO = USER_TELEFONO, 
            EMAIL = USER_EMAIL,
            FECHA_ACTUALIZACION = SYSDATE
        WHERE ID_USUARIO = USER_ID;
        
        COMMIT;
    END UPDATE_USUARIO;

    -- ACTUALIZAR ACCESO USUARIO
    PROCEDURE UPDATE_USUARIO_ACCESO(
        USER_ID IN NUMBER,
        USER_USUARIO IN VARCHAR2,
        USER_PASSWORD IN VARCHAR2,
        USER_ESTADO IN VARCHAR2
    )
    AS
    BEGIN
        UPDATE TA_USUARIOS 
        SET 
            USUARIO = USER_USUARIO, 
            PASSWORD_HASH = USER_PASSWORD, 
            ESTADO = USER_ESTADO,
