CREATE TABLE TA_CARRITO (
    ID_CARRITO NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ID_USUARIO NUMBER NOT NULL UNIQUE,
    FECHA_CREACION DATE DEFAULT SYSDATE,
    FECHA_ACTUALIZACION DATE DEFAULT SYSDATE,
    CONSTRAINT FK_CARRITO_USER FOREIGN KEY (ID_USUARIO) REFERENCES TA_USUARIOS(ID_USUARIO) ON DELETE CASCADE
);

CREATE TABLE TA_CARRITO_ITEMS (
    ID_CARRITO_ITEM NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ID_CARRITO NUMBER NOT NULL,
    ID_PRODUCTO NUMBER NOT NULL,
    CANTIDAD NUMBER NOT NULL,
    PRECIO_UNITARIO NUMBER(10,2) NOT NULL,
    FECHA_AGREGADO DATE DEFAULT SYSDATE,
