CREATE TABLE TA_REGALOS (
    ID_REGALO NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    NOMBRE VARCHAR2(150) NOT NULL,
    DESCRIPCION VARCHAR2(500),
    VALOR_EQUIVALENTE NUMBER(10,2),
    STOCK NUMBER DEFAULT 0,
    STOCK_MIN NUMBER DEFAULT 0,
    IMAGEN BLOB,
    ESTADO VARCHAR2(15) DEFAULT 'ACTIVO', -- ACTIVO, INACTIVO, AGOTADO, DESCONTINUADO
    FECHA_CREACION DATE DEFAULT SYSDATE,
