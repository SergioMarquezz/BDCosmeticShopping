-- ========================================
-- BASE DE DATOS: TIENDA DE COSMÉTICOS
-- Diseño normalizado (1NF, 2NF, 3NF)
-- ========================================

-- ========================================
-- TABLAS DE SEGURIDAD Y USUARIOS
-- ========================================

CREATE TABLE TA_ROLES(
    ID_ROL NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    NOMBRE_ROL VARCHAR2(50) NOT NULL UNIQUE,
    DESCRIPCION VARCHAR2(255)
);

-- TABLA DE USUARIOS (Normalizada - Sin campos redundantes)
CREATE TABLE TA_USUARIOS (
    ID_USUARIO NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ID_ROL NUMBER NOT NULL,
    NOMBRE VARCHAR2(50) NOT NULL,
    AP_PATERNO VARCHAR2(50) NOT NULL,
    AP_MATERNO VARCHAR2(50) NOT NULL,
    FECHA_NACIMIENTO DATE,
    TELEFONO VARCHAR2(20) NOT NULL,
    USUARIO VARCHAR2(50) UNIQUE NOT NULL,
    EMAIL VARCHAR2(100) UNIQUE NOT NULL,
    PASSWORD_HASH VARCHAR2(255) NOT NULL,
    ESTADO VARCHAR2(15) DEFAULT 'ACTIVO', -- ACTIVO, INACTIVO, BLOQUEADO
    FECHA_CREACION DATE DEFAULT SYSDATE,
    FECHA_ACTUALIZACION DATE DEFAULT SYSDATE,
    USUARIO_ACTUALIZACION VARCHAR2(50),
    CONSTRAINT FK_ROL_USER FOREIGN KEY (ID_ROL) REFERENCES TA_ROLES(ID_ROL),
    CONSTRAINT CK_USUARIO_EMAIL CHECK (EMAIL LIKE '%@%.%'),
    CONSTRAINT CK_USUARIO_ESTADO CHECK (ESTADO IN ('ACTIVO', 'INACTIVO', 'BLOQUEADO','BAJA'))
);

CREATE TABLE TA_SESIONES (
    ID_SESION NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ID_USUARIO NUMBER NOT NULL,
    FECHA DATE DEFAULT SYSDATE,
    HORA TIMESTAMP DEFAULT SYSTIMESTAMP,
    IP VARCHAR2(45),
    DISPOSITIVO VARCHAR2(100),
    ESTADO VARCHAR2(15) DEFAULT 'ACTIVA', -- ACTIVA, CERRADA
    CONSTRAINT FK_SESION_USER FOREIGN KEY (ID_USUARIO) REFERENCES TA_USUARIOS(ID_USUARIO) ON DELETE CASCADE
);

CREATE TABLE TA_PERMISOS (
    ID_PERMISO NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    NOMBRE VARCHAR2(50) NOT NULL UNIQUE,
    DESCRIPCION VARCHAR2(200)
);

CREATE TABLE TA_PERMISO_USUARIO (
    ID_USUARIO NUMBER,
    ID_PERMISO NUMBER,
    CONSTRAINT PK_PERMISO_USUARIO PRIMARY KEY (ID_USUARIO, ID_PERMISO),
    CONSTRAINT FK_PU_USER FOREIGN KEY (ID_USUARIO) REFERENCES TA_USUARIOS(ID_USUARIO) ON DELETE CASCADE,
    CONSTRAINT FK_PU_PERMISO FOREIGN KEY (ID_PERMISO) REFERENCES TA_PERMISOS(ID_PERMISO) ON DELETE CASCADE
);

-- ========================================
-- TABLA DE DIRECCIONES DE USUARIOS
-- ========================================

CREATE TABLE TA_DIRECCION_USUARIOS (
    ID_DIRECCION NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ID_USUARIO NUMBER NOT NULL,
    CALLE VARCHAR2(100) NOT NULL,
    NUMERO VARCHAR2(10) NOT NULL,
    COLONIA VARCHAR2(100) NOT NULL,
    CIUDAD VARCHAR2(50) NOT NULL,
    ESTADO VARCHAR2(50) NOT NULL,
    CODIGO_POSTAL VARCHAR2(10) NOT NULL,
    TIPO_DIRECCION VARCHAR2(20) DEFAULT 'ENVÍO', -- ENVÍO, FACTURACIÓN
    FECHA_CREACION DATE DEFAULT SYSDATE,
    FECHA_ACTUALIZACION DATE DEFAULT SYSDATE,
    CONSTRAINT FK_DIR_USER FOREIGN KEY (ID_USUARIO) REFERENCES TA_USUARIOS(ID_USUARIO) ON DELETE CASCADE,
    CONSTRAINT CK_TIPO_DIR CHECK (TIPO_DIRECCION IN ('ENVÍO', 'FACTURACIÓN')),
);

-- ========================================
-- TABLAS DE CATÁLOGO DE PRODUCTOS
-- ========================================

CREATE TABLE TA_BENEFICIOS (
    ID_BENEFICIO NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    NOMBRE VARCHAR2(100) NOT NULL UNIQUE,
    DESCRIPCION VARCHAR2(255),
    FECHA_CREACION DATE DEFAULT SYSDATE
);

CREATE TABLE TA_PROVEEDORES (
    ID_PROVEEDOR NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    NOMBRE VARCHAR2(150) NOT NULL UNIQUE,
    TELEFONO VARCHAR2(20),
    EMAIL VARCHAR2(100),
    ESTADO_PROVEEDOR VARCHAR2(15) DEFAULT 'ACTIVO', -- ACTIVO, INACTIVO, SUSPENDIDO
    FECHA_CREACION DATE DEFAULT SYSDATE,
    FECHA_ACTUALIZACION DATE DEFAULT SYSDATE,
    CONSTRAINT CK_PROVEEDOR_EMAIL CHECK (EMAIL LIKE '%@%.%' OR EMAIL IS NULL),
    CONSTRAINT CK_ESTADO_PROV CHECK (ESTADO_PROVEEDOR IN ('ACTIVO', 'INACTIVO', 'SUSPENDIDO', 'BLOQUEADO'))
);

CREATE TABLE TA_CATEGORIAS (
    ID_CATEGORIA NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    NOMBRE VARCHAR2(100) NOT NULL UNIQUE,
    DESCRIPCION VARCHAR2(200),
    ESTADO VARCHAR2(15) DEFAULT 'ACTIVO',
    FECHA_CREACION DATE DEFAULT SYSDATE,
    CONSTRAINT CK_CAT_ESTADO CHECK (ESTADO IN ('ACTIVO', 'INACTIVO'))
);

CREATE TABLE TA_MARCAS (
    ID_MARCA NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    NOMBRE VARCHAR2(100) NOT NULL UNIQUE,
    DESCRIPCION VARCHAR2(255),
    LOGOTIPO BLOB,
    ESTADO VARCHAR2(15) DEFAULT 'ACTIVO',
    FECHA_CREACION DATE DEFAULT SYSDATE,
    CONSTRAINT CK_MARCA_ESTADO CHECK (ESTADO IN ('ACTIVO', 'INACTIVO'))
);

-- ========================================
-- TABLA DE PRODUCTOS (Normalizada - Sin BENEFICIOS aquí)
-- ========================================

CREATE TABLE TA_PRODUCTOS (
    ID_PRODUCTO NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ID_CATEGORIA NUMBER NOT NULL,
    ID_MARCA NUMBER,
    ID_PROVEEDOR NUMBER,
    NOMBRE VARCHAR2(150) NOT NULL,
    DESCRIPCION VARCHAR2(500),
    CODIGO VARCHAR2(50) UNIQUE NOT NULL,
    PRECIO NUMBER(10,2) NOT NULL,
    PRECIO_COSTO NUMBER(10,2),
    IMAGEN BLOB,
    ESTADO VARCHAR2(15) DEFAULT 'ACTIVO', -- ACTIVO, INACTIVO, DESCONTINUADO
    FECHA_CREACION DATE DEFAULT SYSDATE,
    FECHA_ACTUALIZACION DATE DEFAULT SYSDATE,
    USUARIO_ACTUALIZACION VARCHAR2(50),
    CONSTRAINT FK_PROD_CAT FOREIGN KEY (ID_CATEGORIA) REFERENCES TA_CATEGORIAS(ID_CATEGORIA),
    CONSTRAINT FK_PROD_MARCA FOREIGN KEY (ID_MARCA) REFERENCES TA_MARCAS(ID_MARCA),
    CONSTRAINT FK_PROD_PROV FOREIGN KEY (ID_PROVEEDOR) REFERENCES TA_PROVEEDORES(ID_PROVEEDOR),
    CONSTRAINT CK_PROD_PRECIO CHECK (PRECIO > 0),
    CONSTRAINT CK_PROD_COSTO CHECK (PRECIO_COSTO >= 0 OR PRECIO_COSTO IS NULL),
    CONSTRAINT CK_PROD_ESTADO CHECK (ESTADO IN ('ACTIVO', 'INACTIVO', 'DESCONTINUADO', 'VENDIDO', 'AGOTADO'))
);

-- TABLA DE JUNCIÓN: Beneficios de Productos (Relación M:M Normalizada)
CREATE TABLE TA_PRODUCTO_BENEFICIOS (
    ID_PRODUCTO NUMBER,
    ID_BENEFICIO NUMBER,
    FECHA_ASIGNACION DATE DEFAULT SYSDATE,
    CONSTRAINT PK_PROD_BENEFI PRIMARY KEY (ID_PRODUCTO, ID_BENEFICIO),
    CONSTRAINT FK_PP_PRODUCT FOREIGN KEY (ID_PRODUCTO) REFERENCES TA_PRODUCTOS(ID_PRODUCTO) ON DELETE CASCADE,
    CONSTRAINT FK_PP_BENEFICIO FOREIGN KEY (ID_BENEFICIO) REFERENCES TA_BENEFICIOS(ID_BENEFICIO) ON DELETE CASCADE
);

-- ========================================
-- TABLA DE INVENTARIO (Mejorada)
-- ========================================

CREATE TABLE TA_INVENTARIO (
    ID_INVENTARIO NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ID_PRODUCTO NUMBER NOT NULL UNIQUE,
    STOCK NUMBER DEFAULT 0,
    STOCK_MIN NUMBER DEFAULT 0,
    STOCK_MAX NUMBER,
    ULTIMA_REPOSICION DATE,
    FECHA_ACTUALIZACION DATE DEFAULT SYSDATE,
    CONSTRAINT FK_INV_PROD FOREIGN KEY (ID_PRODUCTO) REFERENCES TA_PRODUCTOS(ID_PRODUCTO) ON DELETE CASCADE,
    CONSTRAINT CK_INV_STOCK CHECK (STOCK >= 0),
    CONSTRAINT CK_INV_MIN_MAX CHECK (STOCK_MIN <= STOCK_MAX OR STOCK_MAX IS NULL)
);

-- ========================================
-- TABLA DE HISTORIAL DE PRECIOS (Nueva - Auditoría)
-- ========================================

CREATE TABLE TA_HISTORIAL_PRECIOS (
    ID_HISTORIAL NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ID_PRODUCTO NUMBER NOT NULL,
    PRECIO_ANTERIOR NUMBER(10,2),
    PRECIO_NUEVO NUMBER(10,2) NOT NULL,
    FECHA_CAMBIO DATE DEFAULT SYSDATE,
    USUARIO_CAMBIO VARCHAR2(50),
    MOTIVO VARCHAR2(255),
    CONSTRAINT FK_HP_PRODUCTO FOREIGN KEY (ID_PRODUCTO) REFERENCES TA_PRODUCTOS(ID_PRODUCTO) ON DELETE CASCADE
);

-- ========================================
-- TABLAS DE VENTAS (Mejoradas)
-- ========================================

CREATE TABLE TA_VENTAS (
    ID_VENTA NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ID_USUARIO NUMBER NOT NULL,
    ID_DIRECCION_ENVIO NUMBER,
    FECHA DATE DEFAULT SYSDATE,
    SUBTOTAL NUMBER(12,2) DEFAULT 0,
    DESCUENTO_TOTAL NUMBER(12,2) DEFAULT 0,
    TOTAL NUMBER(12,2),
    ESTADO_VENTA VARCHAR2(20) DEFAULT 'PENDIENTE', -- PENDIENTE, CONFIRMADA, ENVIADA, ENTREGADA, CANCELADA
    METODO_PAGO VARCHAR2(30), -- TARJETA, TRANSFERENCIA, EFECTIVO, BILLETERA
    NUMERO_PEDIDO VARCHAR2(50) UNIQUE,
    OBSERVACIONES VARCHAR2(500),
    FECHA_CREACION DATE DEFAULT SYSDATE,
    FECHA_ACTUALIZACION DATE DEFAULT SYSDATE,
    USUARIO_ACTUALIZACION VARCHAR2(50),
    CONSTRAINT FK_VENTA_USER FOREIGN KEY (ID_USUARIO) REFERENCES TA_USUARIOS(ID_USUARIO),
    CONSTRAINT FK_VENTA_DIR FOREIGN KEY (ID_DIRECCION_ENVIO) REFERENCES TA_DIRECCION_USUARIOS(ID_DIRECCION),
    CONSTRAINT CK_VENTA_ESTADO CHECK (ESTADO_VENTA IN ('PENDIENTE', 'CONFIRMADA', 'ENVIADA', 'ENTREGADA', 'CANCELADA')),
    CONSTRAINT CK_METODO_PAGO CHECK (METODO_PAGO IN ('TARJETA', 'TRANSFERENCIA', 'EFECTIVO', 'BILLETERA')),
    CONSTRAINT CK_VENTA_TOTAL CHECK (TOTAL >= 0)
);

CREATE TABLE TA_VENTA_DETALLE (
    ID_DETALLE NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ID_VENTA NUMBER NOT NULL,
    ID_PRODUCTO NUMBER NOT NULL,
    CANTIDAD NUMBER NOT NULL,
    PRECIO NUMBER(10,2) NOT NULL,
    SUBTOTAL NUMBER(12,2),
    DESCUENTO_LINEA NUMBER(12,2) DEFAULT 0,
    TOTAL_LINEA NUMBER(12,2),
    CONSTRAINT FK_DET_VENTA FOREIGN KEY (ID_VENTA) REFERENCES TA_VENTAS(ID_VENTA) ON DELETE CASCADE,
    CONSTRAINT FK_DET_VENTA_PROD FOREIGN KEY (ID_PRODUCTO) REFERENCES TA_PRODUCTOS(ID_PRODUCTO),
    CONSTRAINT CK_DETALLE_CANTIDAD CHECK (CANTIDAD > 0),
    CONSTRAINT CK_DETALLE_PRECIO CHECK (PRECIO >= 0)
);

-- TABLA DE JUNCIÓN: Promociones aplicadas a Ventas
CREATE TABLE TA_VENTA_PROMOCION (
    ID_VENTA NUMBER,
    ID_PROMOCION NUMBER,
    DESCUENTO_APLICADO NUMBER(12,2),
    FECHA_APLICACION DATE DEFAULT SYSDATE,
    CONSTRAINT PK_VENTA_PROMO PRIMARY KEY (ID_VENTA, ID_PROMOCION),
    CONSTRAINT FK_VP_VENTA FOREIGN KEY (ID_VENTA) REFERENCES TA_VENTAS(ID_VENTA) ON DELETE CASCADE,
    CONSTRAINT FK_VP_PROMO FOREIGN KEY (ID_PROMOCION) REFERENCES TA_PROMOCIONES(ID_PROMOCION)
);

-- ========================================
-- TABLAS DE COMPRAS A PROVEEDORES (Mejoradas)
-- ========================================

CREATE TABLE TA_COMPRA_PROVEEDOR (
    ID_COMPRA NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ID_PROVEEDOR NUMBER NOT NULL,
    NUMERO_ORDEN VARCHAR2(50) UNIQUE,
    FECHA DATE DEFAULT SYSDATE,
    FECHA_ENTREGA_ESPERADA DATE,
    SUBTOTAL NUMBER(12,2) DEFAULT 0,
    IMPUESTO NUMBER(12,2) DEFAULT 0,
    TOTAL NUMBER(12,2),
    ESTADO VARCHAR2(20) DEFAULT 'PENDIENTE', -- PENDIENTE, CONFIRMADA, ENVIADA, RECIBIDA, CANCELADA
    OBSERVACIONES VARCHAR2(500),
    FECHA_CREACION DATE DEFAULT SYSDATE,
    FECHA_ACTUALIZACION DATE DEFAULT SYSDATE,
    USUARIO_CREACION VARCHAR2(50),
    CONSTRAINT FK_COMPRA_PROV FOREIGN KEY (ID_PROVEEDOR) REFERENCES TA_PROVEEDORES(ID_PROVEEDOR),
    CONSTRAINT CK_COMPRA_ESTADO CHECK (ESTADO IN ('PENDIENTE', 'CONFIRMADA', 'ENVIADA', 'RECIBIDA', 'CANCELADA')),
    CONSTRAINT CK_COMPRA_TOTAL CHECK (TOTAL >= 0)
);

CREATE TABLE TA_COMPRA_PROVEEDOR_DETALLE (
    ID_DETALLE NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ID_COMPRA NUMBER NOT NULL,
    ID_PRODUCTO NUMBER NOT NULL,
    CANTIDAD NUMBER NOT NULL,
    PRECIO NUMBER(10,2) NOT NULL,
    SUBTOTAL NUMBER(12,2),
    CANTIDAD_RECIBIDA NUMBER DEFAULT 0,
    CONSTRAINT FK_CPD_COMPRA FOREIGN KEY (ID_COMPRA) REFERENCES TA_COMPRA_PROVEEDOR(ID_COMPRA) ON DELETE CASCADE,
    CONSTRAINT FK_CPD_PRODUCTO FOREIGN KEY (ID_PRODUCTO) REFERENCES TA_PRODUCTOS(ID_PRODUCTO),
    CONSTRAINT CK_COMP_CANTIDAD CHECK (CANTIDAD > 0),
    CONSTRAINT CK_COMP_PRECIO CHECK (PRECIO >= 0),
    CONSTRAINT CK_CANT_RECIBIDA CHECK (CANTIDAD_RECIBIDA <= CANTIDAD)
);

-- ========================================
-- TABLA DE PROMOCIONES (Mejorada)
-- ========================================

CREATE TABLE TA_PROMOCIONES (
    ID_PROMOCION NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    NOMBRE VARCHAR2(150) NOT NULL,
    DESCRIPCION VARCHAR2(500),
    TIPO_DESCUENTO VARCHAR2(20), -- PORCENTAJE, CANTIDAD
    VALOR_DESCUENTO NUMBER(10,2) NOT NULL,
    CANTIDAD_MINIMA NUMBER DEFAULT 0, -- Monto mínimo para aplicar
    FECHA_INICIO DATE NOT NULL,
    FECHA_FIN DATE NOT NULL,
    CODIGO_PROMOCION VARCHAR2(50) UNIQUE,
    ESTADO VARCHAR2(15) DEFAULT 'ACTIVO', -- ACTIVO, INACTIVO, FINALIZADO, SUSPENDIDO
    FECHA_CREACION DATE DEFAULT SYSDATE,
    USUARIO_CREACION VARCHAR2(50),
    CONSTRAINT CK_TIPO_DESC CHECK (TIPO_DESCUENTO IN ('PORCENTAJE', 'CANTIDAD')),
    CONSTRAINT CK_PROMO_FECHAS CHECK (FECHA_INICIO < FECHA_FIN),
    CONSTRAINT CK_PROMO_ESTADO CHECK (ESTADO IN ('ACTIVO', 'INACTIVO', 'FINALIZADO', 'SUSPENDIDO'))
);

CREATE TABLE TA_PROMOCION_PRODUCTO (
    ID_PROMOCION NUMBER,
    ID_PRODUCTO NUMBER,
    CONSTRAINT PK_PROMO_PROD PRIMARY KEY (ID_PROMOCION, ID_PRODUCTO),
    CONSTRAINT FK_PP_PROMO FOREIGN KEY (ID_PROMOCION) REFERENCES TA_PROMOCIONES(ID_PROMOCION) ON DELETE CASCADE,
    CONSTRAINT FK_PP_PROD FOREIGN KEY (ID_PRODUCTO) REFERENCES TA_PRODUCTOS(ID_PRODUCTO) ON DELETE CASCADE
);

-- ========================================
-- TABLAS DE REGALOS (Nuevas - Requeridas)
