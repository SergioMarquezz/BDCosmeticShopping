CREATE OR REPLACE PACKAGE PKG_REPORTES AS
    -- VENTAS POR RANGO DE FECHAS
    PROCEDURE SP_VENTAS_POR_FECHAS(
        P_FECHA_INICIO IN DATE,
        P_FECHA_FIN IN DATE,
        P_CURSOR OUT SYS_REFCURSOR
    );
    
    -- PRODUCTOS MÁS VENDIDOS
    PROCEDURE SP_PRODUCTOS_MAS_VENDIDOS(
        P_CANTIDAD_REGISTROS IN NUMBER DEFAULT 10,
        P_CURSOR OUT SYS_REFCURSOR
    );
    
    -- CLIENTES MÁS ACTIVOS
    PROCEDURE SP_CLIENTES_MAS_ACTIVOS(
        P_CANTIDAD_REGISTROS IN NUMBER DEFAULT 10,
        P_CURSOR OUT SYS_REFCURSOR
    );
    
    -- RESUMEN DE VENTAS DIARIAS
    PROCEDURE SP_RESUMEN_VENTAS_DIARIAS(
        P_FECHA IN DATE,
        P_CURSOR OUT SYS_REFCURSOR
    );
    
    -- INVENTARIO BAJO
    PROCEDURE SP_INVENTARIO_BAJO(
        P_CURSOR OUT SYS_REFCURSOR
    );
    
END PKG_REPORTES;

CREATE OR REPLACE PACKAGE BODY PKG_REPORTES AS

    -- VENTAS POR RANGO DE FECHAS
    PROCEDURE SP_VENTAS_POR_FECHAS(
        P_FECHA_INICIO IN DATE,
        P_FECHA_FIN IN DATE,
        P_CURSOR OUT SYS_REFCURSOR
    ) 
    AS
    BEGIN
        OPEN P_CURSOR FOR
            SELECT 
                v.ID_VENTA, v.NUMERO_PEDIDO, v.FECHA, 
                u.NOMBRE, u.EMAIL,
                v.SUBTOTAL, v.DESCUENTO_TOTAL, v.IMPUESTO, v.TOTAL,
                v.ESTADO_VENTA, v.METODO_PAGO
            FROM TA_VENTAS v
            LEFT JOIN TA_USUARIOS u ON v.ID_USUARIO = u.ID_USUARIO
            WHERE v.FECHA BETWEEN P_FECHA_INICIO AND P_FECHA_FIN
            ORDER BY v.FECHA DESC;
    END SP_VENTAS_POR_FECHAS;

    -- PRODUCTOS MÁS VENDIDOS
    PROCEDURE SP_PRODUCTOS_MAS_VENDIDOS(
        P_CANTIDAD_REGISTROS IN NUMBER DEFAULT 10,
        P_CURSOR OUT SYS_REFCURSOR
    ) 
    AS
    BEGIN
        OPEN P_CURSOR FOR
            SELECT 
                p.ID_PRODUCTO, p.NOMBRE, p.CODIGO, p.PRECIO,
                SUM(vd.CANTIDAD) AS CANTIDAD_VENDIDA,
                SUM(vd.TOTAL_LINEA) AS INGRESOS_TOTALES
            FROM TA_VENTA_DETALLE vd
            JOIN TA_PRODUCTOS p ON vd.ID_PRODUCTO = p.ID_PRODUCTO
            JOIN TA_VENTAS v ON vd.ID_VENTA = v.ID_VENTA
            WHERE v.ESTADO_VENTA != 'CANCELADA'
            GROUP BY p.ID_PRODUCTO, p.NOMBRE, p.CODIGO, p.PRECIO
            ORDER BY CANTIDAD_VENDIDA DESC
            FETCH FIRST P_CANTIDAD_REGISTROS ROWS ONLY;
    END SP_PRODUCTOS_MAS_VENDIDOS;

    -- CLIENTES MÁS ACTIVOS
    PROCEDURE SP_CLIENTES_MAS_ACTIVOS(
        P_CANTIDAD_REGISTROS IN NUMBER DEFAULT 10,
        P_CURSOR OUT SYS_REFCURSOR
    ) 
    AS
    BEGIN
        OPEN P_CURSOR FOR
            SELECT 
                u.ID_USUARIO, u.NOMBRE, u.EMAIL, u.TELEFONO,
                COUNT(v.ID_VENTA) AS NUMERO_COMPRAS,
                SUM(v.TOTAL) AS MONTO_TOTAL,
                MAX(v.FECHA) AS ULTIMA_COMPRA
            FROM TA_USUARIOS u
            LEFT JOIN TA_VENTAS v ON u.ID_USUARIO = v.ID_USUARIO
            WHERE u.ESTADO = 'ACTIVO'
            GROUP BY u.ID_USUARIO, u.NOMBRE, u.EMAIL, u.TELEFONO
            HAVING COUNT(v.ID_VENTA) > 0
            ORDER BY MONTO_TOTAL DESC
            FETCH FIRST P_CANTIDAD_REGISTROS ROWS ONLY;
    END SP_CLIENTES_MAS_ACTIVOS;

    -- RESUMEN DE VENTAS DIARIAS
    PROCEDURE SP_RESUMEN_VENTAS_DIARIAS(
        P_FECHA IN DATE,
        P_CURSOR OUT SYS_REFCURSOR
    ) 
    AS
    BEGIN
        OPEN P_CURSOR FOR
            SELECT 
                COUNT(ID_VENTA) AS NUMERO_VENTAS,
                SUM(SUBTOTAL) AS SUBTOTAL_DIA,
                SUM(DESCUENTO_TOTAL) AS DESCUENTOS_DIA,
                SUM(IMPUESTO) AS IMPUESTOS_DIA,
                SUM(TOTAL) AS TOTAL_DIA,
                AVG(TOTAL) AS PROMEDIO_VENTA
            FROM TA_VENTAS
            WHERE TRUNC(FECHA) = TRUNC(P_FECHA) AND ESTADO_VENTA != 'CANCELADA';
    END SP_RESUMEN_VENTAS_DIARIAS;

    -- INVENTARIO BAJO
    PROCEDURE SP_INVENTARIO_BAJO(
        P_CURSOR OUT SYS_REFCURSOR
    ) 
    AS
    BEGIN
        OPEN P_CURSOR FOR
            SELECT 
                p.ID_PRODUCTO, p.NOMBRE, p.CODIGO, p.PRECIO_COSTO, p.PRECIO,
                i.STOCK, i.STOCK_MIN, i.STOCK_MAX,
                CASE 
                    WHEN i.STOCK <= i.STOCK_MIN THEN 'REORDEN URGENTE'
                    WHEN i.STOCK <= (i.STOCK_MIN * 1.5) THEN 'STOCK BAJO'
                    ELSE 'OK'
                END AS ESTADO_STOCK,
                c.NOMBRE AS CATEGORIA
            FROM TA_INVENTARIO i
            JOIN TA_PRODUCTOS p ON i.ID_PRODUCTO = p.ID_PRODUCTO
            LEFT JOIN TA_CATEGORIAS c ON p.ID_CATEGORIA = c.ID_CATEGORIA
            WHERE i.STOCK <= (i.STOCK_MIN * 1.5) AND p.ESTADO = 'ACTIVO'
            ORDER BY i.STOCK ASC;
    END SP_INVENTARIO_BAJO;

END PKG_REPORTES;
