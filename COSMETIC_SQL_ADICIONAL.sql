CREATE OR REPLACE PACKAGE PKG_CARRITO AS
    -- OBTENER O CREAR CARRITO
    PROCEDURE SP_GET_CARRITO(
        P_ID_USUARIO IN NUMBER,
        P_ID_CARRITO OUT NUMBER
    );
    
    -- AGREGAR ITEM AL CARRITO
    PROCEDURE SP_AGREGAR_ITEM_CARRITO(
        P_ID_USUARIO IN NUMBER,
        P_ID_PRODUCTO IN NUMBER,
        P_CANTIDAD IN NUMBER
    );
    
    -- ACTUALIZAR CANTIDAD ITEM
    PROCEDURE SP_ACTUALIZAR_ITEM_CARRITO(
        P_ID_CARRITO_ITEM IN NUMBER,
        P_CANTIDAD IN NUMBER
    );
    
    -- ELIMINAR ITEM DEL CARRITO
    PROCEDURE SP_ELIMINAR_ITEM_CARRITO(
        P_ID_CARRITO_ITEM IN NUMBER
    );
    
    -- LISTAR ITEMS DEL CARRITO
    PROCEDURE SP_LISTAR_CARRITO(
        P_ID_USUARIO IN NUMBER,
        P_CURSOR OUT SYS_REFCURSOR
    );
    
    -- VACIAR CARRITO
    PROCEDURE SP_VACIAR_CARRITO(
        P_ID_USUARIO IN NUMBER
    );
    
END PKG_CARRITO;

CREATE OR REPLACE PACKAGE BODY PKG_CARRITO AS

    -- OBTENER O CREAR CARRITO
    PROCEDURE SP_GET_CARRITO(
        P_ID_USUARIO IN NUMBER,
        P_ID_CARRITO OUT NUMBER
    ) 
    AS
    BEGIN
        BEGIN
            SELECT ID_CARRITO INTO P_ID_CARRITO FROM TA_CARRITO WHERE ID_USUARIO = P_ID_USUARIO;
        EXCEPTION
            WHEN NO_DATA_FOUND THEN
                INSERT INTO TA_CARRITO (ID_USUARIO) VALUES (P_ID_USUARIO)
                RETURNING ID_CARRITO INTO P_ID_CARRITO;
                COMMIT;
        END;
    END SP_GET_CARRITO;

    -- AGREGAR ITEM AL CARRITO
    PROCEDURE SP_AGREGAR_ITEM_CARRITO(
        P_ID_USUARIO IN NUMBER,
        P_ID_PRODUCTO IN NUMBER,
        P_CANTIDAD IN NUMBER
    ) 
    AS
        V_ID_CARRITO NUMBER;
        V_PRECIO NUMBER;
    BEGIN
        SP_GET_CARRITO(P_ID_USUARIO, V_ID_CARRITO);
        
        SELECT PRECIO INTO V_PRECIO FROM TA_PRODUCTOS WHERE ID_PRODUCTO = P_ID_PRODUCTO;
        
        INSERT INTO TA_CARRITO_ITEMS (ID_CARRITO, ID_PRODUCTO, CANTIDAD, PRECIO_UNITARIO)
        VALUES (V_ID_CARRITO, P_ID_PRODUCTO, P_CANTIDAD, V_PRECIO);
        
        UPDATE TA_CARRITO SET FECHA_ACTUALIZACION = SYSDATE WHERE ID_CARRITO = V_ID_CARRITO;
        
        COMMIT;
    END SP_AGREGAR_ITEM_CARRITO;

    -- ACTUALIZAR CANTIDAD ITEM
    PROCEDURE SP_ACTUALIZAR_ITEM_CARRITO(
        P_ID_CARRITO_ITEM IN NUMBER,
        P_CANTIDAD IN NUMBER
    ) 
    AS
    BEGIN
        UPDATE TA_CARRITO_ITEMS 
        SET CANTIDAD = P_CANTIDAD
        WHERE ID_CARRITO_ITEM = P_ID_CARRITO_ITEM;
        
        COMMIT;
    END SP_ACTUALIZAR_ITEM_CARRITO;

    -- ELIMINAR ITEM DEL CARRITO
    PROCEDURE SP_ELIMINAR_ITEM_CARRITO(
        P_ID_CARRITO_ITEM IN NUMBER
    ) 
    AS
    BEGIN
        DELETE FROM TA_CARRITO_ITEMS WHERE ID_CARRITO_ITEM = P_ID_CARRITO_ITEM;
        COMMIT;
    END SP_ELIMINAR_ITEM_CARRITO;

    -- LISTAR ITEMS DEL CARRITO
    PROCEDURE SP_LISTAR_CARRITO(
        P_ID_USUARIO IN NUMBER,
        P_CURSOR OUT SYS_REFCURSOR
    ) 
    AS
    BEGIN
        OPEN P_CURSOR FOR
            SELECT 
                ci.ID_CARRITO_ITEM, p.ID_PRODUCTO, p.NOMBRE, p.CODIGO,
                ci.CANTIDAD, ci.PRECIO_UNITARIO, 
                (ci.CANTIDAD * ci.PRECIO_UNITARIO) AS SUBTOTAL,
                p.ESTADO
            FROM TA_CARRITO_ITEMS ci
            JOIN TA_CARRITO c ON ci.ID_CARRITO = c.ID_CARRITO
            JOIN TA_PRODUCTOS p ON ci.ID_PRODUCTO = p.ID_PRODUCTO
            WHERE c.ID_USUARIO = P_ID_USUARIO
            ORDER BY ci.FECHA_AGREGADO;
    END SP_LISTAR_CARRITO;

    -- VACIAR CARRITO
    PROCEDURE SP_VACIAR_CARRITO(
        P_ID_USUARIO IN NUMBER
    ) 
    AS
        V_ID_CARRITO NUMBER;
    BEGIN
        SELECT ID_CARRITO INTO V_ID_CARRITO FROM TA_CARRITO WHERE ID_USUARIO = P_ID_USUARIO;
        
        DELETE FROM TA_CARRITO_ITEMS WHERE ID_CARRITO = V_ID_CARRITO;
        
        UPDATE TA_CARRITO SET FECHA_ACTUALIZACION = SYSDATE WHERE ID_CARRITO = V_ID_CARRITO;
        
        COMMIT;
    END SP_VACIAR_CARRITO;

END PKG_CARRITO;

