-- ========================================
-- PAQUETE PARA MANEJO DE REGALOS
-- ========================================

CREATE OR REPLACE PACKAGE PKG_REGALOS AS
    -- CREAR REGALO
    PROCEDURE SP_CREAR_REGALO(
        P_NOMBRE IN VARCHAR2,
        P_DESCRIPCION IN VARCHAR2,
        P_VALOR_EQUIVALENTE IN NUMBER,
        P_STOCK IN NUMBER
    );
    
    -- ASIGNAR REGALO A CLIENTE
    PROCEDURE SP_ASIGNAR_REGALO_CLIENTE(
        P_ID_USUARIO IN NUMBER,
        P_ID_REGALO IN NUMBER,
        P_FECHA_VENCIMIENTO IN DATE DEFAULT NULL,
        P_ID_VENTA IN NUMBER DEFAULT NULL
    );
    
    -- CANJEAR REGALO
    PROCEDURE SP_CANJEAR_REGALO(
        P_ID_CLIENTE_REGALO IN NUMBER
    );
    
    -- LISTAR REGALOS DISPONIBLES DEL CLIENTE
    PROCEDURE SP_LISTAR_REGALOS_CLIENTE(
        P_ID_USUARIO IN NUMBER,
        P_CURSOR OUT SYS_REFCURSOR
    );
    
    -- LISTAR TODOS LOS REGALOS
    PROCEDURE SP_LISTAR_REGALOS(
        P_CURSOR OUT SYS_REFCURSOR
    );
    
END PKG_REGALOS;

CREATE OR REPLACE PACKAGE BODY PKG_REGALOS AS

    -- CREAR REGALO
    PROCEDURE SP_CREAR_REGALO(
        P_NOMBRE IN VARCHAR2,
        P_DESCRIPCION IN VARCHAR2,
        P_VALOR_EQUIVALENTE IN NUMBER,
        P_STOCK IN NUMBER
    ) 
    AS
    BEGIN
        INSERT INTO TA_REGALOS (NOMBRE, DESCRIPCION, VALOR_EQUIVALENTE, STOCK, STOCK_MIN, ESTADO)
        VALUES (P_NOMBRE, P_DESCRIPCION, P_VALOR_EQUIVALENTE, P_STOCK, ROUND(P_STOCK * 0.1), 'ACTIVO');
        
        COMMIT;
    END SP_CREAR_REGALO;

    -- ASIGNAR REGALO A CLIENTE
    PROCEDURE SP_ASIGNAR_REGALO_CLIENTE(
        P_ID_USUARIO IN NUMBER,
        P_ID_REGALO IN NUMBER,
        P_FECHA_VENCIMIENTO IN DATE DEFAULT NULL,
        P_ID_VENTA IN NUMBER DEFAULT NULL
    ) 
    AS
    BEGIN
        INSERT INTO TA_CLIENTE_REGALOS 
            (ID_USUARIO, ID_REGALO, ID_VENTA, FECHA_VENCIMIENTO, ESTADO)
        VALUES 
            (P_ID_USUARIO, P_ID_REGALO, P_ID_VENTA, P_FECHA_VENCIMIENTO, 'DISPONIBLE');
        
        -- Decrementar stock del regalo
        UPDATE TA_REGALOS SET STOCK = STOCK - 1 WHERE ID_REGALO = P_ID_REGALO;
        
        COMMIT;
    END SP_ASIGNAR_REGALO_CLIENTE;

    -- CANJEAR REGALO
    PROCEDURE SP_CANJEAR_REGALO(
        P_ID_CLIENTE_REGALO IN NUMBER
    ) 
    AS
    BEGIN
        UPDATE TA_CLIENTE_REGALOS 
        SET ESTADO = 'CANJEADO',
            FECHA_CANJE = SYSDATE
        WHERE ID_CLIENTE_REGALO = P_ID_CLIENTE_REGALO;
        
        COMMIT;
    END SP_CANJEAR_REGALO;

    -- LISTAR REGALOS DISPONIBLES DEL CLIENTE
    PROCEDURE SP_LISTAR_REGALOS_CLIENTE(
        P_ID_USUARIO IN NUMBER,
        P_CURSOR OUT SYS_REFCURSOR
    ) 
    AS
    BEGIN
        OPEN P_CURSOR FOR
            SELECT 
                cr.ID_CLIENTE_REGALO, r.NOMBRE, r.DESCRIPCION, r.VALOR_EQUIVALENTE,
                cr.FECHA_OBTENCION, cr.FECHA_VENCIMIENTO, cr.ESTADO, cr.OBSERVACIONES
            FROM TA_CLIENTE_REGALOS cr
            JOIN TA_REGALOS r ON cr.ID_REGALO = r.ID_REGALO
            WHERE cr.ID_USUARIO = P_ID_USUARIO AND cr.ESTADO IN ('DISPONIBLE', 'CANJEADO')
            ORDER BY cr.FECHA_OBTENCION DESC;
    END SP_LISTAR_REGALOS_CLIENTE;

    -- LISTAR TODOS LOS REGALOS
    PROCEDURE SP_LISTAR_REGALOS(
        P_CURSOR OUT SYS_REFCURSOR
    ) 
    AS
    BEGIN
        OPEN P_CURSOR FOR
            SELECT 
                ID_REGALO, NOMBRE, DESCRIPCION, VALOR_EQUIVALENTE, STOCK, STOCK_MIN, ESTADO
            FROM TA_REGALOS
            WHERE ESTADO = 'ACTIVO'
            ORDER BY NOMBRE;
    END SP_LISTAR_REGALOS;

END PKG_REGALOS;

